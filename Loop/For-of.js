const numbers = [50, 14, 555, 55, 71, 22 ]
console.log(numbers); // [50, 14, 555, 55, 71, 22 ]

for(const num of numbers){
    console.log(num);
}

const fruits = ['apple', 'banana', 'bedana', 'kola', 'jaam']
console.log(fruits); // [ 'apple', 'banana', 'bedana', 'kola', 'jaam' ]

for(const fruit of fruits) {
    console.log(fruit); 
}