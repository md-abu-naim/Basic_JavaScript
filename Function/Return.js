function tenTimes(number){
    const ten = number * 10
    return ten
}

const output = tenTimes(50)
console.log(output);


const bigNumber = tenTimes(1000)
console.log(bigNumber);


function doMath(num, num2){
    const sum = num + num2
    const diff = sum - num2
    return diff
}

const bill = doMath(10, 51)
console.log(bill);