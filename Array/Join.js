const friends = [ 'kalam', 'salam', 'balam', 'khailam' ]
console.log(friends); // [ 'kalam', 'salam', 'balam', 'khailam' ]

console.log(friends.join()); // kalam, salam, balam, khailam
console.log(friends.join('')); // kalamsalambalamkhailam
console.log(friends.join('+')); // kalam+salam+balam+khailam
console.log(friends.join('|')); // kalam|salam|balam|khailam